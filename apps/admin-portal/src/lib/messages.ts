/**
 * Languages written right to left.
 *
 * A layout decision rather than a translation one, which is why it lives
 * beside the catalogs and not inside them: the platform's own language
 * registry (`core/locales.py`) carries the same fact for the backend, and the
 * portal reads it from the session — this is the fallback for a language the
 * session has not described.
 */
export const RTL_LANGUAGES = new Set(["ar", "fa", "he", "ur"]);

export function isRtl(language: string | null | undefined): boolean {
  return RTL_LANGUAGES.has((language ?? "en").split("-")[0].toLowerCase());
}
