/**
 * The portal's message catalogs (DEMO-013 §6, completed by DEMO-014 §6–§7).
 *
 * One file, keyed by language, keys namespaced by area. English is both the
 * default and the reference: a key missing from another catalog falls back to
 * it, so a partial translation degrades to a working screen rather than to
 * blanks.
 *
 * **Keys, not sentences, are the interface.** A component asks for
 * `nav.customers`; it never asks what country it is in. That is the whole
 * point — Arabic arrived as a third object below and not as a branch anywhere.
 *
 * **What is deliberately NOT here.** Money, dates, currency codes, document
 * numbers and anything a customer typed. An amount is formatted from an exact
 * decimal string (`components/money.tsx`) at its currency's own scale
 * (`core/money.py`), and a date is rendered in the organization's timezone.
 * Putting any of them in a catalog would invite a translator to change a
 * number, and `RCP-2026-000011` is not a word in any language.
 *
 * All three catalogs carry the same keys, and `localization.test.tsx` fails if
 * they ever stop doing so — a catalog that has quietly stopped keeping up
 * degrades silently, which is exactly the kind of rot a test should catch
 * rather than a person.
 */

