async def test_one_dairys_receivables_are_invisible_to_another(client):
    """Reporting SELECTs across modules; it must not select across tenants."""
    admin_a, who_a, _worth = await _ledger(client)
    admin_b = await _second_tenant(client)
    await _customer(client, admin_b, "Other Dairy Household")

    theirs = (await client.get("/v1/reports/receivables?owing_only=false", headers=admin_b)).json()
    assert [row["name"] for row in theirs["items"]] == ["Other Dairy Household"]
    assert Decimal(theirs["total_outstanding"]) == Decimal("0.00")

    summary_b = (await client.get("/v1/reports/sales/summary", headers=admin_b)).json()
    assert summary_b["total_customers"] == 1
    assert Decimal(summary_b["receivable"]) == Decimal("0.00")

    summary_a = (await client.get("/v1/reports/sales/summary", headers=admin_a)).json()
    assert summary_a["total_customers"] == len(who_a)
    assert Decimal(summary_a["receivable"]) > Decimal("0.00")
