async def test_the_outstanding_total_covers_every_match_not_just_the_page(client):
    """The regression that would make a real dairy's debt look small.

    Twelve debtors, a page of five. Summing the page gives five customers'
    worth of debt and looks entirely plausible — which is why it has to be
    asserted rather than eyeballed.
    """
    _org, admin = await _tenant_admin(client)
    expected = Decimal("0.00")
    for n in range(12):
        customer = await _customer(client, admin, f"Debtor {n:02d}", rate=f"{50 + n}.0000")
        expected += await _deliver(client, admin, customer["id"], 3)
        await _bill(client, admin, customer["id"], 3)

    page = (await client.get("/v1/reports/receivables?limit=5", headers=admin)).json()
    assert len(page["items"]) == 5
    assert page["total"] == 12
    assert Decimal(page["total_outstanding"]) == expected
    assert Decimal(page["total_outstanding"]) > sum(
        Decimal(row["outstanding"]) for row in page["items"]
    )

    # And the count is a count of customers, not the square of one — the shape
    # a duplicated subquery produces, which reads as 144 rather than 12.
    everyone = (await client.get("/v1/reports/receivables?limit=100", headers=admin)).json()
    assert everyone["total"] == 12 and len(everyone["items"]) == 12
    assert Decimal(everyone["total_outstanding"]) == expected


async def test_receivables_pages_without_repeating_or_dropping_a_customer(client):
    _org, admin = await _tenant_admin(client)
    for n in range(12):
        customer = await _customer(client, admin, f"Debtor {n:02d}", rate=f"{50 + n}.0000")
        await _deliver(client, admin, customer["id"], 3)
        await _bill(client, admin, customer["id"], 3)

    seen: list[str] = []
    for offset in (0, 5, 10):
        page = (
            await client.get(f"/v1/reports/receivables?limit=5&offset={offset}", headers=admin)
        ).json()
        seen.extend(row["code"] for row in page["items"])
    assert len(seen) == 12 and len(set(seen)) == 12


