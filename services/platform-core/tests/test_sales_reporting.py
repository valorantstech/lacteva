async def test_receivables_lists_only_customers_who_owe_worst_first(client):
    admin, who, worth = await _ledger(client)
    page = (await client.get("/v1/reports/receivables", headers=admin)).json()

    names = [row["name"] for row in page["items"]]
    assert names == ["Unpaid Household", "Part Paid Household"]
    assert page["total"] == 2
    # The settled customer is absent, and so is the one who was never billed.
    assert "Fully Paid Household" not in names
    assert "Delivered Not Billed" not in names

    unpaid, part = page["items"]
    assert Decimal(unpaid["outstanding"]) == worth[who["unpaid"]["id"]]
    assert Decimal(part["outstanding"]) == worth[who["part"]["id"]] - Decimal("100.00")
    assert part["last_payment_at"] is not None
    assert unpaid["last_payment_at"] is None
    assert unpaid["open_invoices"] == 1
    assert unpaid["oldest_unpaid_from"] == str(TODAY - timedelta(days=4))


