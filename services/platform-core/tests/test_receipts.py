def _runner():
    from platform_core.core import db
    from platform_core.modules.event_relay.consumers import ConsumerRunner

    return ConsumerRunner(db.get_session_factory())


async def _receipts():
    from platform_core.core import db
    from platform_core.modules.receipt.models import Receipt

    async with db.get_session_factory()() as s:
        return list((await s.scalars(select(Receipt).order_by(Receipt.generated_at))).all())


async def _complete_payment(client, headers, payment_id, *, reference="BNK-1"):
    for action, body in (
        ("submit", {}),
        ("execute", {}),
        ("complete", {"reference": reference}),
    ):
        r = await _action(client, headers, payment_id, action, body)
        assert r.status_code == 200, r.text


async def _receipted(client, *, reference="MPESA-77"):
    """A completed payment whose receipt has been generated by the consumer."""
    headers, center, supplier, settlement = await _payable(client)
    payment = await _pay(client, headers, settlement, method="MOBILE_MONEY")
    await _complete_payment(client, headers, payment["id"], reference=reference)
    await _runner().run_once()
    page = (await client.get("/v1/receipts", headers=headers)).json()
    assert page["total"] == 1, page
    return headers, center, supplier, settlement, payment, page["items"][0]


async def _detail(client, headers, receipt_id) -> dict:
    r = await client.get(f"/v1/receipts/{receipt_id}", headers=headers)
    assert r.status_code == 200, r.text
    return r.json()


