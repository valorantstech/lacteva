async def test_receipt_covers_multiple_settlements(client):
    headers, center, supplier, october = await _payable(client)
    november = await _second_settlement(client, headers, center, supplier)
    payment = (
        await _create_payment(
            client,
            headers,
            supplier["id"],
            [{"settlement_id": october["id"]}, {"settlement_id": november["id"]}],
        )
    ).json()
    await _complete_payment(client, headers, payment["id"])
    await _runner().run_once()

    page = (await client.get("/v1/receipts", headers=headers)).json()
    assert page["total"] == 1  # one payment, one receipt
    receipt = page["items"][0]
    assert receipt["line_count"] == 2
    detail = await _detail(client, headers, receipt["id"])
    numbers = {line["settlement_number"] for line in detail["lines"]}
    assert numbers == {october["settlement_number"], november["settlement_number"]}
    # Receipt gross is the sum of the settlements it covers.
    expected_gross = Decimal(october["gross_amount"]) + Decimal(november["gross_amount"])
    assert Decimal(receipt["gross_amount"]) == expected_gross
    assert Decimal(receipt["net_amount"]) == Decimal(payment["amount"])


