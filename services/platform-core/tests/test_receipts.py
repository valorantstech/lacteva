async def test_renderer_is_swappable(client, renderer_guard):
    """The abstraction is the point: a deployment registers its own engine."""
    from platform_core.modules.receipt.rendering import RenderedReceipt

    class _FakePdf:
        name = "fake-pdf"
        format = "pdf"
        content_type = "application/pdf"

        def render(self, receipt):
            return RenderedReceipt(
                format="pdf",
                content_type="application/pdf",
                filename=f"{receipt['receipt_number']}.pdf",
                body="%PDF-1.7 real engine",
            )

    renderer_guard.register_renderer(_FakePdf())
    headers, _center, _supplier, _settlement, _payment, receipt = await _receipted(client)
    body = (
        await client.get(f"/v1/receipts/{receipt['id']}/render?format=pdf", headers=headers)
    ).json()
    assert body["content_type"] == "application/pdf"
    assert body["body"].startswith("%PDF-1.7")
    assert body["placeholder"] is False


