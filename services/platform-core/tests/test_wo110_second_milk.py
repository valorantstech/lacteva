# --- §2: what he has next ----------------------------------------------------------------


async def test_the_delivery_boy_is_told_what_he_has_next(client):
    org, owner = await _fresh_shop(client, slug="patel-next")
    boy = await _delivery_boy(
        client, owner, org["id"], email="boy@patel.example", full_name="Ramesh Pawar"
    )
    driver = await _my_driver(client, boy)
    # Nothing known yet.
    r = await client.get("/v1/delivery-runs/mine/next", headers=boy)
    assert r.status_code == 200 and r.json()["business_date"] is None, r.text

    a101 = await _customer(client, owner, "A-101")
    b204 = await _customer(client, owner, "B-204")
    route = await _round(
        client, owner, name="Morning round", stops=[a101["id"], b204["id"]], driver_id=driver["id"]
    )
    # His round auto-plans: expected on the next working day, two stops.
    r = await client.patch(f"/v1/routes/{route['id']}", json={"auto_plan": True}, headers=owner)
    assert r.status_code == 200, r.text
    r = await client.get("/v1/delivery-runs/mine/next", headers=boy)
    assert r.status_code == 200, r.text
    me_org = (await client.get("/v1/auth/me", headers=owner)).json()
    today = datetime.now(ZoneInfo(me_org["organization"]["timezone"])).date()
    expected = r.json()
    assert expected["planned"] is False and expected["stops"] == 2
    assert (
        today
        < datetime.fromisoformat(expected["business_date"]).date()
        <= today + timedelta(days=7)
    )
    assert expected["route_name"] == "Morning round"

    # A run the office already planned for a later day answers first.
    later = today + timedelta(days=3)
    r = await client.post(
        "/v1/delivery-runs",
        json={
            "route_id": route["id"],
            "driver_id": driver["id"],
            "business_date": later.isoformat(),
        },
        headers=owner,
    )
    assert r.status_code == 201, r.text
    r = await client.get("/v1/delivery-runs/mine/next", headers=boy)
    assert r.json()["planned"] is True and r.json()["business_date"] == later.isoformat()
    assert r.json()["stops"] == 2
