# --- §7: covering for an absent boy ----------------------------------------------------


async def test_covering_for_an_absent_boy_shows_the_run_on_the_other_phone(client):
    env = await _walk(client, "patel-cover")
    owner, run = env["owner"], env["run"]
    suresh = await _delivery_boy(
        client, owner, env["org"]["id"], email="suresh@patel.example", full_name="Suresh Pawar"
    )
    suresh_driver = await _my_driver(client, suresh)
    assert (await client.get("/v1/delivery-runs/mine", headers=suresh)).json() == []

    r = await client.post(
        f"/v1/delivery-runs/{run['id']}/assignment",
        json={"driver_id": suresh_driver["id"]},
        headers=owner,
    )
    assert r.status_code == 200, r.text
