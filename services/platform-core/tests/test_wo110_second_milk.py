async def _two_milk_household(client, owner, name):
    """B-204: 0.5 L buffalo AND 1 L cow — WO-81's C-1603, WO-107's second order."""
    r = await client.post(
        "/v1/customers",
        json={
            "name": name,
            "plan": {"product": "BUFFALO-MILK", "default_quantity": "0.5", "unit_price": "90"},
        },
        headers=owner,
    )
    assert r.status_code == 201, r.text
    household = r.json()
    r = await client.post(
        f"/v1/customers/{household['id']}/plan",
        json={"product": "COW-MILK", "default_quantity": "1", "unit_price": "70"},
        headers=owner,
    )
    assert r.status_code == 201, r.text
    return household


async def _round(client, owner, *, name, stops, driver_id, transport="on foot"):
    r = await client.post("/v1/routes", json={"name": name, "transport": transport}, headers=owner)
    assert r.status_code == 201, r.text
    route = r.json()
    r = await client.put(
        f"/v1/routes/{route['id']}/stops", json={"customer_ids": stops}, headers=owner
    )
    assert r.status_code == 200, r.text
    r = await client.patch(
        f"/v1/routes/{route['id']}", json={"default_driver_id": driver_id}, headers=owner
    )
    assert r.status_code == 200, r.text
    return route


async def _todays_run(client, owner, route, driver_id):
    """The office plans today's run and generates its deliveries."""
    r = await client.post(
        "/v1/delivery-runs", json={"route_id": route["id"], "driver_id": driver_id}, headers=owner
    )
    assert r.status_code == 201, r.text
    run = r.json()
    r = await client.post(f"/v1/delivery-runs/{run['id']}/generate", headers=owner)
    assert r.status_code == 201, r.text
    return run, r.json()


async def _my_driver(client, boy):
    r = await client.get("/v1/drivers/me", headers=boy)
    assert r.status_code == 200, r.text
    return r.json()


async def _walk(client, slug):
    """The owner's exact round: A-101 (1 L cow) and B-204 (cow AND buffalo)."""
    org, owner = await _fresh_shop(client, slug=slug)
    boy = await _delivery_boy(
        client, owner, org["id"], email=f"boy-{slug}@patel.example", full_name="Mutahhar Pathan"
    )
    driver = await _my_driver(client, boy)
    a101 = await _customer(client, owner, "A-101")
    b204 = await _two_milk_household(client, owner, "B-204")
    route = await _round(
        client,
        owner,
        name="Sunrise Tower morning",
        stops=[a101["id"], b204["id"]],
        driver_id=driver["id"],
    )
    run, generated = await _todays_run(client, owner, route, driver["id"])
    assert generated["created"] == 3, generated  # two stops, THREE deliveries
    return {
        "org": org,
        "owner": owner,
        "boy": boy,
        "driver": driver,
        "a101": a101,
        "b204": b204,
        "route": route,
        "run": run,
    }


async def _mine(client, boy):
    r = await client.get("/v1/delivery-runs/mine", headers=boy)
    assert r.status_code == 200, r.text
    assert len(r.json()) == 1, r.json()
    return r.json()[0]


def _stop(run, customer):
    return next(s for s in run["stops"] if s["customer_id"] == customer["id"])


async def _outcome(client, boy, run, customer, **body):
    return await client.post(
        f"/v1/delivery-runs/{run['id']}/stops/{customer['id']}/outcome",
        json={"status": "delivered", **body},
        headers=boy,
    )


# --- §1: the second milk ---------------------------------------------------------


async def test_a_two_milk_stop_needs_both_outcomes_before_the_run_can_complete(client):
    env = await _walk(client, "patel-two-milks")
    boy, owner, run = env["boy"], env["owner"], env["run"]

    mine = await _mine(client, boy)
    # The run counts DELIVERIES: two stops, three of them, all scheduled.
    assert (
        mine["deliveries_total"],
        mine["deliveries_scheduled"],
        mine["deliveries_recorded"],
    ) == (
        3,
        3,
        0,
    )
    b204 = _stop(mine, env["b204"])
    assert {o["product"]: o["delivery_status"] for o in b204["orders"]} == {
        "BUFFALO-MILK": "scheduled",
        "COW-MILK": "scheduled",
    }
    assert b204["delivery_status"] == "scheduled"

    r = await client.post(f"/v1/delivery-runs/{run['id']}/start", headers=boy)
    assert r.status_code == 200, r.text

    # The phone records ONE outcome at B-204 — the cow — exactly as the old
    # APK does. The stop stays OPEN: an older phone counting stops keeps it
    # in front of the delivery boy instead of walking on.
    r = await _outcome(client, boy, run, env["b204"], product="COW-MILK")
    assert r.status_code == 201, r.text
    mine = await _mine(client, boy)
    b204 = _stop(mine, env["b204"])
    assert b204["delivery_status"] == "scheduled", "one milk of two is not a recorded stop"
    assert {o["product"]: o["delivery_status"] for o in b204["orders"]} == {
        "BUFFALO-MILK": "scheduled",
        "COW-MILK": "delivered",
    }
    assert (mine["deliveries_scheduled"], mine["deliveries_recorded"]) == (2, 1)
    # A second bare tap on the stop is told which milk is missing, not ignored.
    r = await _outcome(client, boy, run, env["b204"])
    assert r.status_code == 409, r.text
    assert "more than one product" in r.text

    # The platform refuses to complete — from the phone AND from the office.
    r = await client.post(f"/v1/delivery-runs/{run['id']}/complete", headers=boy)
    assert r.status_code == 409, r.text
    assert "still scheduled" in r.text
    assert env["b204"]["code"] in r.text and "BUFFALO-MILK" in r.text
    assert env["a101"]["code"] in r.text and "COW-MILK" in r.text
    r = await client.post(
        f"/v1/delivery-runs/{run['id']}/status", json={"status": "completed"}, headers=owner
    )
    assert r.status_code == 409, r.text
    assert (await _mine(client, boy))["status"] == "in_progress"

    # Both milks and the other stop recorded — the buffalo at its 0.5 L —
    # and the run completes; every delivery reached a bill-able state.
    r = await _outcome(client, boy, run, env["b204"], product="BUFFALO-MILK")
    assert r.status_code == 201, r.text
    r = await _outcome(client, boy, run, env["a101"])
    assert r.status_code == 201, r.text
    r = await client.post(f"/v1/delivery-runs/{run['id']}/complete", headers=boy)
    assert r.status_code == 200, r.text
    mine = await _mine(client, boy)
    assert mine["status"] == "completed"
    assert (mine["deliveries_scheduled"], mine["deliveries_recorded"]) == (0, 3)
    b204 = _stop(mine, env["b204"])
    assert b204["delivery_status"] == "delivered"
    by_product = {o["product"]: o for o in b204["orders"]}
    assert Decimal(by_product["BUFFALO-MILK"]["quantity_delivered"]) == Decimal("0.500")
    assert Decimal(by_product["COW-MILK"]["quantity_delivered"]) == Decimal("1.000")
    rows = (
        await client.get(
            "/v1/deliveries",
            params={
                "date_from": mine["business_date"],
                "date_to": mine["business_date"],
                "limit": 50,
            },
            headers=owner,
        )
    ).json()["items"]
    assert all(d["status"] == "delivered" for d in rows) and len(rows) == 3
    # A-101's cow at the helper's ₹50, B-204's cow at ₹70 and buffalo 0.5 L at ₹90.
    assert sum(Decimal(d["amount"]) for d in rows) == Decimal("50") + Decimal("70") + Decimal("45")


async def test_a_single_milk_stop_is_unchanged_and_an_office_completion_still_works(client):
    """The one-milk household records with one tap as before, and the office
    can complete a run every delivery of which is recorded."""
    env = await _walk(client, "patel-one-milk")
    boy, owner, run = env["boy"], env["owner"], env["run"]
    await client.post(f"/v1/delivery-runs/{run['id']}/start", headers=boy)
    assert (await _outcome(client, boy, run, env["a101"])).status_code == 201
    assert (await _outcome(client, boy, run, env["b204"], product="COW-MILK")).status_code == 201
    r = await _outcome(client, boy, run, env["b204"], product="BUFFALO-MILK", status="skipped")
    assert r.status_code == 201, r.text
    # A skipped milk is RECORDED — the run may close.
    r = await client.post(
        f"/v1/delivery-runs/{run['id']}/status", json={"status": "completed"}, headers=owner
    )
    assert r.status_code == 200, r.text
    mine = await _mine(client, boy)
    assert _stop(mine, env["b204"])["delivery_status"] == "delivered"


# --- §2: correcting from the door --------------------------------------------------


async def test_a_wrong_quantity_is_corrected_from_the_door_until_a_bill_takes_it(client):
    env = await _walk(client, "patel-correct")
    boy, owner, run = env["boy"], env["owner"], env["run"]
    await client.post(f"/v1/delivery-runs/{run['id']}/start", headers=boy)
    assert (await _outcome(client, boy, run, env["a101"])).status_code == 201
    # "I poured one and a half, not one" — recorded again from the same door.
    r = await _outcome(client, boy, run, env["a101"], quantity="1.500")
    assert r.status_code == 201, r.text
    mine = await _mine(client, boy)
    order = _stop(mine, env["a101"])["orders"][0]
    assert Decimal(order["quantity_delivered"]) == Decimal("1.500")
    assert order["invoiced"] is False
    # Or "that was actually skipped".
    r = await _outcome(client, boy, run, env["a101"], status="skipped")
    assert r.status_code == 201, r.text
    assert _stop(await _mine(client, boy), env["a101"])["delivery_status"] == "skipped"
    r = await _outcome(client, boy, run, env["a101"], quantity="1.000")
    assert r.status_code == 201, r.text

    # Once a bill has taken the row, the door may look but not change it.
    day = mine["business_date"]
    r = await client.post(
        "/v1/invoices",
        json={"customer_id": env["a101"]["id"], "period_from": day, "period_to": day},
        headers=owner,
    )
    assert r.status_code == 201, r.text
    mine = await _mine(client, boy)
    assert _stop(mine, env["a101"])["orders"][0]["invoiced"] is True
    r = await _outcome(client, boy, run, env["a101"], quantity="2.000")
    assert r.status_code == 409, r.text
    assert "invoice" in r.text


# --- §4: mark the rest as delivered ------------------------------------------------


async def test_mark_the_rest_as_delivered_leaves_recorded_outcomes_alone(client):
    env = await _walk(client, "patel-rest")
    boy, owner, run = env["boy"], env["owner"], env["run"]
    # A third household, so the batch has more than one delivery to mark.
    c305 = await _customer(client, owner, "C-305")
    r = await client.put(
        f"/v1/routes/{env['route']['id']}/stops",
        json={"customer_ids": [env["a101"]["id"], env["b204"]["id"], c305["id"]]},
        headers=owner,
    )
    assert r.status_code == 200, r.text
    r = await client.post(f"/v1/delivery-runs/{run['id']}/generate", headers=owner)
    assert r.status_code == 201 and r.json()["created"] == 1, r.text
    await client.post(f"/v1/delivery-runs/{run['id']}/start", headers=boy)

    # Two manual outcomes first: A-101 took less, C-305 was not home.
    assert (await _outcome(client, boy, run, env["a101"], quantity="0.750")).status_code == 201
    assert (await _outcome(client, boy, run, c305, status="skipped")).status_code == 201

    # Another boy's phone cannot mark this run.
    stranger = await _delivery_boy(
        client, owner, env["org"]["id"], email="other@patel.example", full_name="Other Boy"
    )
    r = await client.post(
        f"/v1/delivery-runs/{run['id']}/outcomes/remaining", json={}, headers=stranger
    )
    assert r.status_code == 404, r.text

    key = str(uuid.uuid4())
    r = await client.post(
        f"/v1/delivery-runs/{run['id']}/outcomes/remaining",
        json={},
        headers={**boy, "Idempotency-Key": key},
    )
    assert r.status_code == 201, r.text
    assert (r.json()["marked"], r.json()["untouched"]) == (2, 2)
    view = r.json()["run"]
    assert (view["deliveries_scheduled"], view["deliveries_recorded"]) == (0, 4)
    # The two recorded by hand are exactly as recorded.
    assert Decimal(_stop(view, env["a101"])["orders"][0]["quantity_delivered"]) == Decimal("0.750")
    assert _stop(view, c305)["delivery_status"] == "skipped"
    # B-204's two milks are delivered at their standing quantities.
    b204 = {o["product"]: o for o in _stop(view, env["b204"])["orders"]}
    assert b204["BUFFALO-MILK"]["delivery_status"] == "delivered"
    assert Decimal(b204["BUFFALO-MILK"]["quantity_delivered"]) == Decimal("0.500")
    assert Decimal(b204["COW-MILK"]["quantity_delivered"]) == Decimal("1.000")

    # A replay with the same key is the same answer; a fresh call finds
    # nothing scheduled and marks nothing — idempotent by construction.
    r = await client.post(
        f"/v1/delivery-runs/{run['id']}/outcomes/remaining",
        json={},
        headers={**boy, "Idempotency-Key": key},
    )
    assert r.status_code == 201 and r.json()["marked"] == 2, r.text
    r = await client.post(f"/v1/delivery-runs/{run['id']}/outcomes/remaining", json={}, headers=boy)
    assert r.status_code == 201, r.text
    assert (r.json()["marked"], r.json()["untouched"]) == (0, 4)

    # One audit line per delivery from the domain that owns it, plus the
    # run's own line saying how many.
    r = await client.get(
        "/v1/audit", params={"action": "sales.delivery.confirmed", "limit": 50}, headers=owner
    )
    assert r.status_code == 200, r.text
    confirmed = [e for e in r.json()["items"] if e["action"] == "sales.delivery.confirmed"]
    assert len(confirmed) >= 4
    r = await client.get(
        "/v1/audit",
        params={"action": "logistics.run_remaining_marked_delivered", "limit": 10},
        headers=owner,
    )
    assert {e["detail"]["marked"] for e in r.json()["items"]} >= {2, 0}
    # And the run completes — after which the door may still CORRECT what it
    # recorded (WO-110 §2: the finished round is reviewable), but not record
    # a household it never visited.
    r = await client.post(f"/v1/delivery-runs/{run['id']}/complete", headers=boy)
    assert r.status_code == 200, r.text
    r = await _outcome(client, boy, run, env["a101"], quantity="1.250")
    assert r.status_code == 201, r.text
    assert Decimal(
        _stop(await _mine(client, boy), env["a101"])["orders"][0]["quantity_delivered"]
    ) == Decimal("1.250")


# --- §5: one household, one round ----------------------------------------------------


async def test_a_household_on_another_active_round_is_moved_not_doubled(client):
    org, owner = await _fresh_shop(client, slug="patel-two-rounds")
    ramesh = await _delivery_boy(
        client, owner, org["id"], email="ramesh@patel.example", full_name="Ramesh Pawar"
    )
    suresh = await _delivery_boy(
        client, owner, org["id"], email="suresh@patel.example", full_name="Suresh Pawar"
    )
    flat = await _customer(client, owner, "Flat C-1603")
    temple = await _customer(client, owner, "Shri Ganesh Mandir")
    first = await _round(
        client,
        owner,
        name="Ramesh morning",
        stops=[flat["id"], temple["id"]],
        driver_id=(await _my_driver(client, ramesh))["id"],
    )
    r = await client.post("/v1/routes", json={"name": "Suresh evening"}, headers=owner)
    second = r.json()

    # The same household on Suresh's round too: refused, naming where it is.
    r = await client.put(
        f"/v1/routes/{second['id']}/stops", json={"customer_ids": [flat["id"]]}, headers=owner
    )
    assert r.status_code == 409, r.text
    assert "Flat C-1603" in r.text and "Ramesh morning" in r.text and "move" in r.text
    assert (await client.get(f"/v1/routes/{second['id']}", headers=owner)).json()["stops"] == []

    # Moved: on Suresh's round now, off Ramesh's, the temple still on Ramesh's.
    r = await client.put(
        f"/v1/routes/{second['id']}/stops",
        json={"customer_ids": [flat["id"]], "move_from_other_rounds": True},
        headers=owner,
    )
    assert r.status_code == 200, r.text
    assert [s["customer_id"] for s in r.json()["stops"]] == [flat["id"]]
    remaining = (await client.get(f"/v1/routes/{first['id']}", headers=owner)).json()["stops"]
    assert [s["customer_id"] for s in remaining] == [temple["id"]]
    r = await client.get(
        "/v1/audit", params={"action": "logistics.route_stop_moved", "limit": 5}, headers=owner
    )
    assert r.json()["items"][0]["detail"]["from_route"] == "Ramesh morning"

    # A round that is no longer active does not hold a household hostage.
    r = await client.patch(f"/v1/routes/{second['id']}", json={"active": False}, headers=owner)
    assert r.status_code == 200, r.text
    r = await client.put(
        f"/v1/routes/{first['id']}/stops",
        json={"customer_ids": [temple["id"], flat["id"]]},
        headers=owner,
    )
    assert r.status_code == 200, r.text
    _ = suresh


# --- §6: a household on no round -----------------------------------------------------


async def test_a_household_on_no_round_is_generated_by_nobody_and_is_now_listed(client):
    org, owner = await _fresh_shop(client, slug="patel-unrouted")
    boy = await _delivery_boy(
        client, owner, org["id"], email="boy@patel.example", full_name="Ramesh Pawar"
    )
    driver = await _my_driver(client, boy)
    a101 = await _customer(client, owner, "A-101")
    d407 = await _customer(client, owner, "D-407")  # a standing order, no round
    route = await _round(
        client, owner, name="Morning round", stops=[a101["id"]], driver_id=driver["id"]
    )
    r = await client.patch(f"/v1/routes/{route['id']}", json={"auto_plan": True}, headers=owner)
    assert r.status_code == 200, r.text

    # The premise, verified: with rounds in use the nightly generator works
    # route by route, so D-407 gets NO delivery row — not a scheduled one,
    # nothing — and nobody's phone will ever show it.
    me_org = (await client.get("/v1/auth/me", headers=owner)).json()
    zone = ZoneInfo(me_org["organization"]["timezone"])
    today = datetime.now(zone).date()
    at = datetime(today.year, today.month, today.day, 0, 31, tzinfo=zone).astimezone(UTC)
    tenant = Tenant(id=uuid.UUID(org["id"]), slug="patel-unrouted", timezone=str(zone))
    generation = await run_for_tenant(
        tenant,
        now=at,
        generation_hour=HOUR,
        force_date=today,
        route_scopes=scheduled_round_scopes,
        route_planner=plan_auto_routes_for_scheduler,
    )
    assert generation is not None and generation.status == "success", generation
    rows = (
        await client.get(
            "/v1/deliveries",
            params={"date_from": today.isoformat(), "date_to": today.isoformat(), "limit": 50},
            headers=owner,
        )
    ).json()["items"]
    assert {d["customer_id"] for d in rows} == {a101["id"]}, "D-407 was generated by nobody"

    # Now it is said out loud: on the rounds page and on the dashboard.
    r = await client.get("/v1/routes/unrouted-customers", headers=owner)
    assert r.status_code == 200, r.text
    assert r.json()["count"] == 1
    assert [c["name"] for c in r.json()["items"]] == ["D-407"]
    dash = (await client.get("/v1/reports/dashboard", headers=owner)).json()
    item = next((i for i in dash["attention"] if i["key"] == "unrouted_customers"), None)
    assert item is not None and item["count"] == 1 and item["href"] == "/routes#unrouted"

    # One tap adds it to the round, and the warning is gone.
    r = await client.put(
        f"/v1/routes/{route['id']}/stops",
        json={"customer_ids": [a101["id"], d407["id"]]},
        headers=owner,
    )
    assert r.status_code == 200, r.text
    assert (await client.get("/v1/routes/unrouted-customers", headers=owner)).json()["count"] == 0
    dash = (await client.get("/v1/reports/dashboard", headers=owner)).json()
    assert all(i["key"] != "unrouted_customers" for i in dash["attention"])

    # A customer whose only plan is paused, or who is inactive, is not "owed a round".
    e508 = await _customer(client, owner, "E-508")
    r = await client.post(
        f"/v1/customers/{e508['id']}/status", json={"status": "inactive"}, headers=owner
    )
    if r.status_code == 404:
        r = await client.patch(
            f"/v1/customers/{e508['id']}", json={"status": "inactive"}, headers=owner
        )
    assert r.status_code in (200, 201), r.text
    assert (await client.get("/v1/routes/unrouted-customers", headers=owner)).json()["count"] == 0


