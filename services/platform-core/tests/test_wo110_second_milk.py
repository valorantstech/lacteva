"""WO-110 · LACTEVA-MOBILE-017 — the delivery boy's round, walked on a real phone.

The owner recorded both stops of a two-stop round on a moto g57 and the run
went to `completed` with "Every stop recorded" — while B-204's buffalo milk
sat `scheduled` at ₹0, never delivered and never billed. Both the phone and
the run counted STOPS. These tests pin the platform's half of the fix, which
has to hold on its own because older APKs stay in the field:

* a run cannot complete while any of its deliveries is still `scheduled`,
  and the refusal names them (§1);
* the stop's one-word status stays `scheduled` while any of its milks is;
* a wrong quantity is corrected from the same door until a bill takes the
  row (§2);
* "Mark the rest as delivered" touches only what is still scheduled and is
  idempotent by construction (§4);
* a household already on another ACTIVE round is moved, never doubled (§5);
* a household with a standing order on NO round is generated by nobody —
  verified — and is now listed and shown on the dashboard (§6);
* covering for an absent boy: the run appears on the other phone (§7);
* what the delivery boy has next (§2).
"""

